"""Compute SPEC-COVERAGE.md from spec front matter (single source of truth = the page spec files)."""
import os, re, json, glob, collections
from gen_common import ASPX, MODULES, MOD, ROOT, table, write

DIMS = ['ui', 'frontend', 'backend', 'api', 'database', 'rules', 'permission', 'status', 'tests']

def read_front(path):
    try:
        t = open(os.path.join(ROOT, path), encoding='utf-8').read(2500)
    except Exception:
        return None
    m = re.search(r'^coverage:\s*(\{.*\})\s*$', t, re.M)
    tier = re.search(r'^tier:\s*(\w+)', t, re.M)
    if not m:
        return {'tier': tier.group(1) if tier else '?', 'cov': {d: 'UNKNOWN' for d in DIMS}, 'parse_error': True}
    try:
        cov = json.loads(m.group(1))
    except Exception:
        cov = {d: 'UNKNOWN' for d in DIMS}
    return {'tier': tier.group(1) if tier else '?', 'cov': cov}

def overall(cov, tier):
    vals = [cov.get(d, 'UNKNOWN') for d in DIMS]
    core = [cov.get(d, 'UNKNOWN') for d in DIMS if d != 'tests']
    if all(v == 'COMPLETE' for v in core) and cov.get('tests') in ('COMPLETE', 'PARTIAL'):
        return 'COMPLETE'
    if sum(v == 'UNKNOWN' or v == 'MISSING' for v in vals) >= 6:
        return 'UNKNOWN' if tier == 'B' else 'PARTIAL'
    return 'PARTIAL'

def main():
    rows = []
    per = collections.defaultdict(lambda: collections.Counter())
    tiers = collections.Counter()
    dimc = collections.defaultdict(collections.Counter)
    for p in ASPX:
        fm = read_front(p['file'])
        if fm is None:
            rows.append([MOD[p['module']][0], f"{p['id']} {p['name']}"] + ['MISSING'] * 9 + ['MISSING'])
            per[p['module']]['MISSING'] += 1
            continue
        cov = fm['cov']
        ov = overall(cov, fm['tier'])
        tiers[fm['tier']] += 1
        per[p['module']][ov] += 1
        per[p['module']]['tier' + fm['tier']] += 1
        for d in DIMS: dimc[d][cov.get(d, 'UNKNOWN')] += 1
        rows.append([p['module'], f"[{p['id']}]({os.path.relpath(p['file'], 'specs').replace(chr(92), '/')}) {p['name']}"] + [cov.get(d, 'UNKNOWN') for d in DIMS] + [ov + f" (Tier {fm['tier']})"])
    t = ['# Spec Coverage', '',
         'Generated by `docs/reverse-engineering/tools/gen_coverage.py` from the `coverage:` front matter of each page spec. A page is **COMPLETE** only when every dimension except tests is COMPLETE *and* tests are at least PARTIAL. '
         '**Tier A** = page reviewed by reading markup, code-behind and the BLL/DAL chain; **Tier B** = mechanically extracted, not semantically reviewed (never COMPLETE). '
         'Dimension values: COMPLETE (fully verified against code), PARTIAL (verified in part), MISSING (nothing exists/extracted), UNKNOWN (cannot be determined from the repository — e.g. stored-procedure bodies absent).', '',
         '## Summary', '',
         f"- Pages with specs: {sum(tiers.values())} / {len(ASPX)}; Tier A: {tiers.get('A', 0)}, Tier B: {tiers.get('B', 0)}",
         f"- Overall COMPLETE: {sum(per[m]['COMPLETE'] for m in per)}; PARTIAL: {sum(per[m]['PARTIAL'] for m in per)}; UNKNOWN: {sum(per[m]['UNKNOWN'] for m in per)}; MISSING: {sum(per[m]['MISSING'] for m in per)}", '',
         '### By module', '',
         table(['Module', 'Pages', 'Tier A', 'Tier B', 'COMPLETE', 'PARTIAL', 'UNKNOWN', 'MISSING'],
               [[f"{m[0]} {m[2]}", sum(1 for p in ASPX if p['module'] == m[0]), per[m[0]]['tierA'], per[m[0]]['tierB'], per[m[0]]['COMPLETE'], per[m[0]]['PARTIAL'], per[m[0]]['UNKNOWN'], per[m[0]]['MISSING']] for m in MODULES]), '',
         '### By dimension (all pages)', '',
         table(['Dimension', 'COMPLETE', 'PARTIAL', 'MISSING', 'UNKNOWN'], [[d, dimc[d]['COMPLETE'], dimc[d]['PARTIAL'], dimc[d]['MISSING'], dimc[d]['UNKNOWN']] for d in DIMS]), '',
         '## Page coverage', '',
         table(['Module', 'Page', 'UI', 'Frontend', 'Backend', 'API', 'Database', 'Rules', 'Permission', 'Status', 'Tests', 'Overall'], rows), '',
         '## Non-page artefacts', '',
         'Master pages, user controls (`IVMarketStructure*.ascx`), handlers (`*.ashx`), web services (`*.asmx`) and app files are inventoried in `docs/reverse-engineering/page-inventory.md` (COMP-nnn ids). They have **no individual specs** (MISSING) except where a module README or integration spec covers them.', '']
    write('specs/SPEC-COVERAGE.md', '\n'.join(t))
    print('coverage', dict(tiers), {m: dict(v) for m, v in per.items()})

if __name__ == '__main__':
    main()
